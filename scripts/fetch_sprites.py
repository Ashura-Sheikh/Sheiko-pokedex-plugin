"""Fetches the 151 Gen 1 sprites into a LOCAL, git-ignored TypeScript file.

Usage:
    python3 -I scripts/fetch_sprites.py src/data/sprites.local.ts
    (or: npm run sprites)

Sheikh chose option S1 (2026-10-12): sprite art is never committed to this repo.
This script writes it only to the output file, which .gitignore excludes. Builds made
on this machine then include the sprites (esbuild.config.mjs picks the local file when
it exists); CI and fresh clones build with the empty map and show placeholder badges.

Source: PokeAPI's sprite repository (the default 96x96 pixel sprites). Every download
is treated as untrusted: it must be a PNG, exactly 96x96 and under 64 KB, or the
script stops without writing anything.
"""

import base64
import concurrent.futures
import os
import struct
import sys
import urllib.request

GEN1_MAX = 151
URL = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/{}.png"
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
MAX_BYTES = 64 * 1024
SIZE = (96, 96)


def check_png(dex, data):
    if len(data) > MAX_BYTES:
        raise ValueError("#%d: %d bytes is over the %d limit" % (dex, len(data), MAX_BYTES))
    if not data.startswith(PNG_SIGNATURE) or data[12:16] != b"IHDR":
        raise ValueError("#%d: not a PNG" % dex)
    width, height = struct.unpack(">II", data[16:24])
    if (width, height) != SIZE:
        raise ValueError("#%d: %dx%d, expected %dx%d" % (dex, width, height, SIZE[0], SIZE[1]))


def fetch(dex):
    with urllib.request.urlopen(URL.format(dex), timeout=30) as r:
        data = r.read(MAX_BYTES + 1)
    check_png(dex, data)
    return dex, data


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    if os.path.basename(out) != "sprites.local.ts":
        sys.exit("refusing to write %s: only sprites.local.ts is git-ignored" % out)

    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        results = dict(pool.map(fetch, range(1, GEN1_MAX + 1)))

    total = sum(len(d) for d in results.values())
    lines = [
        "// GENERATED by scripts/fetch_sprites.py. LOCAL ONLY: git-ignored, never commit (S1, 2026-10-12).",
        "// 151 PokeAPI pixel sprites as data URIs. Delete this file to build without sprites.",
        "",
        "export const SPRITES: Readonly<Record<number, string>> = {",
    ]
    for dex in range(1, GEN1_MAX + 1):
        b64 = base64.b64encode(results[dex]).decode("ascii")
        lines.append("\t%d: 'data:image/png;base64,%s'," % (dex, b64))
    lines.append("};")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d sprites (%.1f KB of PNG) to %s" % (len(results), total / 1024, out))


if __name__ == "__main__":
    main()
