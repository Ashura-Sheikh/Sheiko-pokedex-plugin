import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { existsSync } from 'node:fs';

// Sprites (S1, Sheikh 2026-10-12): the art lives only in the git-ignored local file made by
// `npm run sprites`. Without it (CI, fresh clones) the empty map is used and badges show instead.
const LOCAL_SPRITES = 'src/data/sprites.local.ts';
const spritesFile = existsSync(LOCAL_SPRITES) ? LOCAL_SPRITES : 'src/data/sprites.none.ts';
console.log(`Sprites: ${spritesFile === LOCAL_SPRITES ? 'local file (sprites included)' : 'none (placeholder badges)'}`);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	alias: { 'sprites-data': './' + spritesFile },
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	// Keep /*! legal comments */ (PokeAPI's BSD-3 notice in src/data/gen1.ts) at the end of
	// main.js, so release users get the notice. Explicit, not left to esbuild's default.
	legalComments: 'eof',
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
