import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

// No sprite art is ever bundled. Users download sprites from the plugin's settings (DB, 0.8.0).

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	// SHEIKO_OUTFILE lets a test build a production bundle somewhere else without touching main.js.
	outfile: process.env.SHEIKO_OUTFILE || 'main.js',
	minify: prod,
	// Development builds keep the unlimited test commands (src/dev-tools.ts); release builds drop them.
	define: { __SHEIKO_DEV__: prod ? 'false' : 'true' },
	// Keep /*! legal comments */ (PokeAPI's BSD-3 notice in src/data/pokedex.ts) at the end of
	// main.js, so release users get the notice. Explicit, not left to esbuild's default.
	legalComments: 'eof',
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
